fig, axes = plt.subplots(1, N_SPLITS, figsize=(4 * N_SPLITS, 4))
colors = plt.cm.tab10(np.linspace(0, 1, len(CLASSES_LIST)))

for fold_i, y_probs_fold in enumerate(all_y_probs):
    # Gather true labels for this fold
    fold_size  = len(y_probs_fold)
    start      = sum(len(all_y_probs[j]) for j in range(fold_i))
    y_true_fold = np.array(all_y_true[start : start + fold_size])
    y_true_oh   = to_categorical(y_true_fold, num_classes=len(CLASSES_LIST))

    ax = axes[fold_i]
    for c_i, cls_name in enumerate(CLASSES_LIST):
        try:
            fpr, tpr, _ = roc_curve(y_true_oh[:, c_i], y_probs_fold[:, c_i])
            auc_val     = roc_auc_score(y_true_oh[:, c_i], y_probs_fold[:, c_i])
            ax.plot(fpr, tpr, color=colors[c_i],
                    label=f'{cls_name} (AUC={auc_val:.2f})')
        except ValueError:
            pass  # Skip class if only one label in test fold

    ax.plot([0,1],[0,1],'k--', linewidth=0.8)
    ax.set_title(f'Fold {fold_i+1} ROC')
    ax.set_xlabel('FPR')
    ax.set_ylabel('TPR')
    ax.legend(fontsize=7)

plt.suptitle('ROC-AUC Curves per Fold (One-vs-Rest)', fontsize=13)
plt.tight_layout()
plt.show()

