    print(f"{'='*60}")

    # ── Splits ────────────────────────────────────────────────────────
    X_train     = features[train_idx]
    y_train_int = labels[train_idx]
    vp_train    = video_files_paths[train_idx]
    X_test      = features[test_idx]
    y_test      = labels[test_idx]

    print(f"  Train dist : {np.bincount(y_train_int, minlength=len(CLASSES_LIST))}")
    print(f"  Test  dist : {np.bincount(y_test, minlength=len(CLASSES_LIST))}")

    # ── Class weights — penalise minority class errors more heavily ───
    cw_values = compute_class_weight(
        class_weight='balanced',
        classes=np.unique(y_train_int),
        y=y_train_int
    )
    class_weight_dict = dict(enumerate(cw_values))
    print(f"  Class weights: { {CLASSES_LIST[k]: round(v,2) for k,v in class_weight_dict.items()} }")

    # One-hot encode
    y_train_oh = to_categorical(y_train_int, num_classes=len(CLASSES_LIST))
    y_test_oh  = to_categorical(y_test,      num_classes=len(CLASSES_LIST))

    # ── Build a FRESH model for this fold ─────────────────────────────
    tf.keras.backend.clear_session()
    encoder = build_lrcn_contextual()

    # ── Contrastive Pre-training (training fold only) ─────────────────
    print("\n  [Pre-training — NT-Logistic contrastive loss]")
    pt_losses = pretrain_contrastive(
        encoder, X_train, vp_train,
        epochs=PRETRAIN_EPOCHS, batch_size=32
    )
    fold_pretrain_loss.append(pt_losses)

    # ── Single-stage Fine-tuning ───────────────────────────────────────
    print("\n  [Fine-tuning — single stage, class-weighted loss]")

    final_model = build_classification_model(encoder, num_classes=len(CLASSES_LIST))

    lr_schedule = tf.keras.optimizers.schedules.CosineDecay(
        initial_learning_rate=FINETUNE_LR,
        decay_steps=FINETUNE_EPOCHS * max(1, len(X_train) // BATCH_SIZE),
        alpha=1e-6
    )

    final_model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=lr_schedule),
        loss=focal_loss(),              # replaces categorical_crossentropy
        metrics=[
            'accuracy',
            tf.keras.metrics.Precision(name='precision'),
            tf.keras.metrics.Recall(name='recall')
        ]
    )

    early_stop = EarlyStopping(
        monitor='val_loss', patience=FINETUNE_PATIENCE,
        restore_best_weights=True, verbose=1
    )

    history = final_model.fit(
        X_train, y_train_oh,
        validation_data=(X_test, y_test_oh),   # ← test fold as val: guaranteed minority samples
        batch_size=BATCH_SIZE,
        epochs=FINETUNE_EPOCHS,
        shuffle=True,
        class_weight=class_weight_dict,         # ← penalise minority errors more
        callbacks=[early_stop],
        verbose=1
    )
    fold_histories.append(history.history)

    # ── Evaluation on test fold ────────────────────────────────────────
    test_loss, test_acc, test_prec, test_rec = final_model.evaluate(
        X_test, y_test_oh, verbose=0
    )
    f1 = (2 * test_prec * test_rec) / (test_prec + test_rec + 1e-7)

    y_probs = final_model.predict(X_test, verbose=0)
    y_pred  = np.argmax(y_probs, axis=1)

    try:
        auc = roc_auc_score(y_test_oh, y_probs, multi_class='ovr', average='macro')
    except ValueError:
        auc = float('nan')

    fold_metrics.append({
        'fold'     : fold + 1,
        'loss'     : test_loss,
        'accuracy' : test_acc,
        'precision': test_prec,
        'recall'   : test_rec,
        'f1'       : f1,
        'auc'      : auc
    })

    all_y_true.extend(y_test.tolist())
    all_y_pred.extend(y_pred.tolist())
    all_y_probs.append(y_probs)

    print(f"\n  Fold {fold+1} Results:")
    print(f"    Accuracy : {test_acc:.4f}")
    print(f"    Precision: {test_prec:.4f}")
    print(f"    Recall   : {test_rec:.4f}")
    print(f"    F1       : {f1:.4f}")
    print(f"    AUC      : {auc:.4f}")

