# -----------------------------------------------------------------------
# Frame Extraction
# -----------------------------------------------------------------------
def frames_extraction(video_path, sequence_length=SEQUENCE_LENGTH, overlap=0):
    sequences = []
    video_reader = cv2.VideoCapture(video_path)

    if not video_reader.isOpened():
        print(f"  ⚠ Skipping (couldn't open): {video_path}")
        video_reader.release()
        return sequences

    video_frames_count = int(video_reader.get(cv2.CAP_PROP_FRAME_COUNT))

    # Fallback for containers that report 0/garbage frame counts
    if video_frames_count <= 0:
        count = 0
        while True:
            success, _ = video_reader.read()
            if not success:
                break
            count += 1
        video_frames_count = count
        video_reader.release()
        video_reader = cv2.VideoCapture(video_path)

    if video_frames_count < sequence_length:
        video_reader.release()
        return sequences

    skip_frames_window = max(int(video_frames_count / sequence_length), 1)

    for start_frame in range(0, video_frames_count - sequence_length + 1, sequence_length - overlap):
        frames = []
        for frame_counter in range(sequence_length):
            video_reader.set(cv2.CAP_PROP_POS_FRAMES, start_frame + frame_counter * skip_frames_window)
            success, frame = video_reader.read()
            if not success:
                break
            resized_frame = cv2.resize(frame, (IMAGE_HEIGHT, IMAGE_WIDTH))
            normalized_frame = resized_frame / 255.0
            frames.append(normalized_frame)
        if len(frames) == sequence_length:
            sequences.append(frames)

    video_reader.release()
    return sequences


# -----------------------------------------------------------------------
# Data Augmentation
# -----------------------------------------------------------------------
def augment_frame(frame):
    # Geometric
    frame = tf.image.random_flip_left_right(frame)
    frame = tf.image.random_flip_up_down(frame)
    # Colour / photometric
    frame = tf.image.random_brightness(frame, max_delta=0.2)
    frame = tf.image.random_contrast(frame, lower=0.8, upper=1.2)
    frame = tf.image.random_saturation(frame, lower=0.8, upper=1.2)
    frame = tf.image.random_hue(frame, max_delta=0.1)
    # Clip to valid range after colour jitter
    frame = tf.clip_by_value(frame, 0.0, 1.0)
    return frame

def augment_sequence(seq):
    return [augment_frame(tf.convert_to_tensor(f, dtype=tf.float32)).numpy() for f in seq]

