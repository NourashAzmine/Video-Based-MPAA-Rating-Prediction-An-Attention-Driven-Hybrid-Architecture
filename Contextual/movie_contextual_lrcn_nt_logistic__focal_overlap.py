# -----------------------------------------------------------------------
# LRCN — Long-term Recurrent Convolutional Network (TimeDistributed CNN + BiLSTM)
# -----------------------------------------------------------------------
def td_conv_block(x, filters, block_id):
    """One TimeDistributed Conv2D -> BN -> ReLU -> MaxPool block, applied
    independently to every frame in the sequence."""
    x = layers.TimeDistributed(
        layers.Conv2D(filters, (3, 3), padding='same', use_bias=False,
                       kernel_regularizer=regularizers.l2(L2_WEIGHT)),
        name=f'td_conv{block_id}')(x)
    x = layers.TimeDistributed(layers.BatchNormalization(), name=f'td_bn{block_id}')(x)
    x = layers.TimeDistributed(layers.ReLU(), name=f'td_relu{block_id}')(x)
    x = layers.TimeDistributed(layers.MaxPooling2D((2, 2), padding='same'),
                                name=f'td_pool{block_id}')(x)
    return x


def build_lrcn_contextual(input_shape=(SEQUENCE_LENGTH, IMAGE_HEIGHT, IMAGE_WIDTH, 3),
                            lstm_units=128):
    """Returns a fresh (untrained) LRCN encoder: a per-frame CNN feature
    extractor feeding a stacked Bidirectional LSTM that outputs a single
    embedding vector per video sequence."""
    inputs = layers.Input(shape=input_shape)

    # ── TimeDistributed CNN feature extractor (per-frame, weight-shared) ──
    x = td_conv_block(inputs, 32,  block_id=1)
    x = td_conv_block(x,      64,  block_id=2)
    x = td_conv_block(x,      128, block_id=3)
    x = td_conv_block(x,      256, block_id=4)

    # Per-frame global pooling → (batch, seq_len, 256)
    x = layers.TimeDistributed(layers.GlobalAveragePooling2D(), name='td_gap')(x)
    x = layers.TimeDistributed(layers.Dropout(DROPOUT_AFTER_GAP), name='td_dropout')(x)  # ← dropout 1

    # ── Temporal modelling: stacked Bidirectional LSTM ──────────────────
    x = layers.Bidirectional(
        layers.LSTM(lstm_units, return_sequences=True,
                    kernel_regularizer=regularizers.l2(L2_WEIGHT)),
        name='bilstm1')(x)
    x = layers.Bidirectional(
        layers.LSTM(lstm_units, return_sequences=False,
                    kernel_regularizer=regularizers.l2(L2_WEIGHT)),
        name='bilstm2')(x)

    x = layers.Dropout(DROPOUT_AFTER_ATT)(x)          # ← dropout 2

    return models.Model(inputs, x)


def build_classification_model(base_model, num_classes=len(CLASSES_LIST)):
    """Adds a softmax classification head on top of the encoder."""
    outputs = Dense(num_classes, activation='softmax')(base_model.output)
    return models.Model(inputs=base_model.input, outputs=outputs)

"""## 3. Contrastive Learning Components"""

# -----------------------------------------------------------------------
# NT-Logistic Contrastive Loss
# -----------------------------------------------------------------------
def nt_logistic_loss(z_i, z_j, temperature=TEMPERATURE):
    z_i = tf.math.l2_normalize(z_i, axis=1)
    z_j = tf.math.l2_normalize(z_j, axis=1)
    representations = tf.concat([z_i, z_j], axis=0)
    similarity_matrix = tf.matmul(representations, representations, transpose_b=True)
    batch_size = tf.shape(z_i)[0]
    N = 2 * batch_size

    labels_pos = tf.concat([tf.range(batch_size) + batch_size, tf.range(batch_size)], axis=0)
    labels_oh  = tf.one_hot(labels_pos, depth=N)     # 1 at the positive-pair location
    mask_self  = tf.eye(N)                             # 1 on the diagonal (self-similarity)

    logits = similarity_matrix / temperature

    # target = +1 for the positive pair, -1 for every negative pair, 0 on the diagonal
    targets = labels_oh - (1.0 - labels_oh - mask_self)

    # -log(sigmoid(target * logit)) == softplus(-target * logit)
    per_pair_loss = tf.nn.softplus(-targets * logits)
    per_pair_loss = per_pair_loss * (1.0 - mask_self)   # exclude self-similarity term

    loss_per_anchor = tf.reduce_sum(per_pair_loss, axis=1)
    return tf.reduce_mean(loss_per_anchor)


# -----------------------------------------------------------------------
# Focal Loss  — replaces categorical_crossentropy in fine-tuning
# -----------------------------------------------------------------------
def focal_loss(gamma=FOCAL_GAMMA, alpha=FOCAL_ALPHA):
    def loss_fn(y_true, y_pred):
        # Clip predictions for numerical stability
        y_pred = tf.clip_by_value(y_pred, 1e-7, 1.0 - 1e-7)

        # Standard cross-entropy per class
        ce = -y_true * tf.math.log(y_pred)

        # pt = probability of the correct class
        pt = tf.reduce_sum(y_true * y_pred, axis=-1, keepdims=True)

        # Focal weight: (1 - pt)^gamma — low for easy samples, high for hard
        focal_weight = alpha * tf.pow(1.0 - pt, gamma)

        # Apply focal weight to cross-entropy
        focal_ce = focal_weight * ce
        return tf.reduce_mean(tf.reduce_sum(focal_ce, axis=-1))
    return loss_fn



# -----------------------------------------------------------------------
# Contextual Pair Mining  (train split only)
# -----------------------------------------------------------------------
def create_contextual_contrastive_pairs(features, video_paths):
    contrastive_pairs = []
    for i in range(len(features)):
        current_seq   = features[i]
        current_video = video_paths[i]

        # Positive pair: two independent augmentations of the same sequence
        aug1 = augment_sequence(current_seq)
        aug2 = augment_sequence(current_seq)
        contrastive_pairs.append((aug1, aug2))

        # Contextual neighbours (same video, adjacent segments)
        if i > 0 and video_paths[i - 1] == current_video:
            contrastive_pairs.append((current_seq, features[i - 1]))
        if i < len(features) - 1 and video_paths[i + 1] == current_video:
            contrastive_pairs.append((current_seq, features[i + 1]))

    return contrastive_pairs


# -----------------------------------------------------------------------
# Contrastive Pre-training  — with best-weight checkpointing
# -----------------------------------------------------------------------
def pretrain_contrastive(model, features, video_paths,
                          epochs=PRETRAIN_EPOCHS, batch_size=32,
                          patience=PRETRAIN_PATIENCE):
    optimizer        = tf.keras.optimizers.Adam()
    epoch_losses     = []
    best_loss        = float('inf')
    best_weights     = None
    best_epoch       = 0
    patience_counter = 0

    for epoch in range(epochs):
        pairs = create_contextual_contrastive_pairs(features, video_paths)
        random.shuffle(pairs)
        batch_losses = []

        for i in range(0, len(pairs), batch_size):
            batch = pairs[i : i + batch_size]
            if len(batch) == 0:
                continue
            seq1 = tf.convert_to_tensor([p[0] for p in batch], dtype=tf.float32)
            seq2 = tf.convert_to_tensor([p[1] for p in batch], dtype=tf.float32)

            with tf.GradientTape() as tape:
                z_i  = model(seq1, training=True)
                z_j  = model(seq2, training=True)
                loss = nt_logistic_loss(z_i, z_j)

            grads = tape.gradient(loss, model.trainable_variables)
            optimizer.apply_gradients(zip(grads, model.trainable_variables))
            batch_losses.append(loss.numpy())

        avg = np.mean(batch_losses)
        epoch_losses.append(avg)

        # ── Best-weight checkpoint ───────────────────────────────────
        if avg < best_loss:
            best_loss        = avg
            best_weights     = model.get_weights()   # snapshot
            best_epoch       = epoch + 1
            patience_counter = 0
            tag = '  ✓ best'
        else:
            patience_counter += 1
            tag = f'  (no improvement {patience_counter}/{patience})'

        print(f"  Pretrain Epoch {epoch+1:3d}/{epochs} — Loss: {avg:.4f}{tag}")

        # ── Early stopping ───────────────────────────────────────────
        if patience_counter >= patience:
            print(f"  Early stopping triggered at epoch {epoch+1}")
            break

    # ── Restore best weights before handing encoder to fine-tuning ──
    if best_weights is not None:
        model.set_weights(best_weights)
        print(f"  Best pre-train loss: {best_loss:.4f} (epoch {best_epoch}) — weights restored ✓")

    return epoch_losses

