# Function to extract, resize, and normalize frames
def frames_extraction(video_path, sequence_length=SEQUENCE_LENGTH, overlap=OVERLAP):
    sequences = []
    video_reader = cv2.VideoCapture(video_path)
    video_frames_count = int(video_reader.get(cv2.CAP_PROP_FRAME_COUNT))
    skip_frames_window = max(int(video_frames_count / sequence_length), 1)

    # Extract overlapping sequences
    for start_frame in range(0, video_frames_count - sequence_length + 1, sequence_length - overlap):
        frames = []
        for frame_counter in range(sequence_length):
            video_reader.set(cv2.CAP_PROP_POS_FRAMES, start_frame + frame_counter * skip_frames_window)
            success, frame = video_reader.read()
            if not success:
                break
            resized_frame = cv2.resize(frame, (IMAGE_HEIGHT, IMAGE_WIDTH))
            normalized_frame = resized_frame / 255
            frames.append(normalized_frame)
        if len(frames) == sequence_length:
            sequences.append(frames)
    video_reader.release()
    return sequences

# Create dataset function
def create_dataset():
    features = []
    labels = []
    video_files_paths = []
    for class_index, class_name in enumerate(CLASSES_LIST):
        print(f'Extracting Data of Class: {class_name}')
        class_dir = os.path.join(DATASET_DIR, class_name)
        files_list = os.listdir(class_dir)
        for file_name in files_list:
            video_file_path = os.path.join(class_dir, file_name)
            sequences = frames_extraction(video_file_path)
            for seq in sequences:
                features.append(seq)
                labels.append(class_index)
                video_files_paths.append(video_file_path)
    features = np.asarray(features)
    labels = np.array(labels)
    return features, labels, video_files_paths

