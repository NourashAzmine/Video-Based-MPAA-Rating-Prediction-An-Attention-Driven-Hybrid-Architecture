# Data augmentation for contrastive learning
def augment_frame(frame):
    frame = tf.image.random_flip_left_right(frame)
    frame = tf.image.random_brightness(frame, max_delta=0.2)
    frame = tf.image.random_contrast(frame, lower=0.8, upper=1.2)
    return frame

# Generate contextual contrastive pairs
def create_contextual_contrastive_pairs(features, video_files_paths):
    contrastive_pairs = []
    num_sequences = len(features)
    for i in range(num_sequences):
        current_seq = features[i]
        current_video = video_files_paths[i]

        # Positive Pair 1: Augmented version of the same sequence
        augmented_seq1 = [augment_frame(frame) for frame in current_seq]
        augmented_seq2 = [augment_frame(frame) for frame in current_seq]
        contrastive_pairs.append((augmented_seq1, augmented_seq2))

        # Positive Pair 2: Adjacent sequences (contextual)
        if i > 0 and video_files_paths[i-1] == current_video:
            adjacent_seq = features[i-1]
            contrastive_pairs.append((current_seq, adjacent_seq))
        if i < num_sequences - 1 and video_files_paths[i+1] == current_video:
            adjacent_seq = features[i+1]
            contrastive_pairs.append((current_seq, adjacent_seq))

    return contrastive_pairs

# ResNet block definition
def res_block(x, filters, kernel_size=(3, 3, 3), stride=(1, 1, 1), block_id=1):
    y = layers.Conv3D(filters, kernel_size, strides=stride, padding='same', use_bias=False,
                      kernel_regularizer=regularizers.l2(1e-5),
                      name=f'conv{block_id}')(x)
    y = layers.BatchNormalization(name=f'bn{block_id}')(y)
    y = layers.ReLU(name=f'relu{block_id}')(y)
    y = layers.Conv3D(filters, kernel_size, padding='same', use_bias=False,
                      kernel_regularizer=regularizers.l2(1e-5),
                      name=f'conv{block_id}_2')(y)
    y = layers.BatchNormalization(name=f'bn{block_id}_2')(y)
    if x.shape[-1] != filters or stride != (1, 1, 1):
        x = layers.Conv3D(filters, (1, 1, 1), strides=stride, padding='same', use_bias=False,
                          kernel_regularizer=regularizers.l2(1e-5),
                          name=f'conv{block_id}_shortcut')(x)
        x = layers.BatchNormalization(name=f'bn{block_id}_shortcut')(x)
    y = layers.add([x, y])
    y = layers.ReLU(name=f'relu{block_id}_out')(y)
    return y

from tensorflow.keras.layers import MultiHeadAttention, LayerNormalization

# Define the entire 3D ResNet-50 model with Contextual Attention for contrastive learning
def build_r3d_50_contextual(input_shape=(20, 64, 64, 3), num_heads=4, key_dim=64):
    inputs = layers.Input(shape=input_shape)
    x = layers.Conv3D(64, (5, 7, 7), strides=(2, 2, 2), padding='same', use_bias=False, name='conv1')(inputs)
    x = layers.BatchNormalization(name='bn1')(x)
    x = layers.ReLU(name='relu1')(x)
    x = layers.MaxPooling3D((1, 3, 3), strides=(1, 2, 2), padding='same', name='pool1')(x)

    x = res_block(x, 64, stride=(1, 1, 1), block_id=2)
    x = res_block(x, 128, stride=(2, 2, 2), block_id=3)
    x = res_block(x, 256, stride=(2, 2, 2), block_id=4)
    x = res_block(x, 512, stride=(2, 2, 2), block_id=5)

    x = layers.GlobalAveragePooling3D(name='gap')(x)

    # Add Temporal Attention
    x = tf.expand_dims(x, axis=1)  # Shape: (batch_size, 1, features)
    attention_output = MultiHeadAttention(num_heads=num_heads, key_dim=key_dim)(x, x)
    attention_output = LayerNormalization()(attention_output + x)
    attention_output = tf.squeeze(attention_output, axis=1)

    model = models.Model(inputs, attention_output)
    return model

# Build the Contextual Contrastive Model
contextual_r3d_contrastive_model = build_r3d_50_contextual()

# NT-Xent loss function
def nt_xent_loss(z_i, z_j, temperature=0.1):
    z_i = tf.math.l2_normalize(z_i, axis=1)
    z_j = tf.math.l2_normalize(z_j, axis=1)

    # Concatenate along the batch dimension
    representations = tf.concat([z_i, z_j], axis=0)

    # Compute similarity matrix
    similarity_matrix = tf.matmul(representations, representations, transpose_b=True)

    # Create labels
    batch_size = tf.shape(z_i)[0]
    labels = tf.concat([tf.range(batch_size) + batch_size, tf.range(batch_size)], axis=0)
    labels = tf.one_hot(labels, depth=2 * batch_size)

    # Mask to remove similarity of samples with themselves
    mask = tf.eye(2 * batch_size)
    similarity_matrix = similarity_matrix / temperature
    logits = similarity_matrix - mask * 1e9  # Large negative to exclude self-similarity

    loss = tf.nn.softmax_cross_entropy_with_logits(labels, logits)
    loss = tf.reduce_mean(loss)
    return loss

# Pretrain the model using Contextual Contrastive Learning
def pretrain_contextual_contrastive_model(model, features, video_files_paths, epochs=10, batch_size=32):
    optimizer = tf.keras.optimizers.Adam()
    for epoch in range(epochs):
        print(f'Starting Epoch {epoch+1}/{epochs}')
        contrastive_pairs = create_contextual_contrastive_pairs(features, video_files_paths)
        random.shuffle(contrastive_pairs)  # Shuffle to ensure randomness

        batch_loss = []
        for i in range(0, len(contrastive_pairs), batch_size):
            batch = contrastive_pairs[i:i + batch_size]
            if len(batch) == 0:
                continue
            # Separate the sequences
            batch_seq1 = [pair[0] for pair in batch]
            batch_seq2 = [pair[1] for pair in batch]

            # Convert to tensors
            batch_seq1 = tf.convert_to_tensor(batch_seq1, dtype=tf.float32)
            batch_seq2 = tf.convert_to_tensor(batch_seq2, dtype=tf.float32)

            with tf.GradientTape() as tape:
                z_i = model(batch_seq1, training=True)
                z_j = model(batch_seq2, training=True)
                loss = nt_xent_loss(z_i, z_j)

            gradients = tape.gradient(loss, model.trainable_variables)
            optimizer.apply_gradients(zip(gradients, model.trainable_variables))
            batch_loss.append(loss.numpy())

        avg_loss = np.mean(batch_loss) if batch_loss else 0
        print(f'Epoch {epoch+1}, Average Loss: {avg_loss:.4f}')

