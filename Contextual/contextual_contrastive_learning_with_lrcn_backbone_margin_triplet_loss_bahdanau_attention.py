# Data augmentation for contrastive learning
def augment_frame(frame):
    frame = tf.image.random_flip_left_right(frame)
    frame = tf.image.random_brightness(frame, max_delta=0.2)
    frame = tf.image.random_contrast(frame, lower=0.8, upper=1.2)
    return frame

# Generate contextual contrastive pairs
def create_contextual_contrastive_pairs(features, video_files_paths):
    contrastive_pairs = []
    num_sequences = len(features)
    for i in range(num_sequences):
        current_seq = features[i]
        current_video = video_files_paths[i]

        # Positive Pair 1: Augmented version of the same sequence
        augmented_seq1 = [augment_frame(frame) for frame in current_seq]
        augmented_seq2 = [augment_frame(frame) for frame in current_seq]
        contrastive_pairs.append((augmented_seq1, augmented_seq2))

        # Positive Pair 2: Adjacent sequences (contextual)
        if i > 0 and video_files_paths[i-1] == current_video:
            adjacent_seq = features[i-1]
            contrastive_pairs.append((current_seq, adjacent_seq))
        if i < num_sequences - 1 and video_files_paths[i+1] == current_video:
            adjacent_seq = features[i+1]
            contrastive_pairs.append((current_seq, adjacent_seq))

    return contrastive_pairs

# 2D CNN for spatial feature extraction from frames
def build_cnn(input_shape=(64, 64, 3)):
    cnn_input = layers.Input(shape=input_shape)
    x = layers.Conv2D(32, (3, 3), activation='relu', padding='same')(cnn_input)
    x = layers.MaxPooling2D((2, 2))(x)
    x = layers.Conv2D(64, (3, 3), activation='relu', padding='same')(x)
    x = layers.MaxPooling2D((2, 2))(x)
    x = layers.Conv2D(128, (3, 3), activation='relu', padding='same')(x)
    x = layers.MaxPooling2D((2, 2))(x)
    x = layers.GlobalAveragePooling2D()(x)  # Compress to single vector per frame
    model = models.Model(inputs=cnn_input, outputs=x)
    return model

# Bahdanau Attention Layer
class BahdanauAttention(tf.keras.layers.Layer):
    def __init__(self, units):
        super(BahdanauAttention, self).__init__()
        self.W1 = tf.keras.layers.Dense(units)
        self.W2 = tf.keras.layers.Dense(units)
        self.V = tf.keras.layers.Dense(1)

    def call(self, query, values):
        # query: the LSTM output, shape (batch_size, hidden_size)
        # values: the LSTM hidden states (time-distributed CNN features), shape (batch_size, sequence_length, hidden_size)

        # Add time axis to query to match the shape of values
        query_with_time_axis = tf.expand_dims(query, 1)

        # Calculate attention scores
        score = self.V(tf.nn.tanh(self.W1(query_with_time_axis) + self.W2(values)))

        # Attention weights (softmax to normalize)
        attention_weights = tf.nn.softmax(score, axis=1)

        # Context vector: weighted sum of values
        context_vector = attention_weights * values
        context_vector = tf.reduce_sum(context_vector, axis=1)

        return context_vector, attention_weights

# LRCN model combining CNN, LSTM, and Bahdanau Attention for video sequence processing
def build_lrcn_with_attention(input_shape=(20, 64, 64, 3), lstm_units=256, attention_units=128, num_classes=4):
    # Input for sequence of frames (20 frames, 64x64 resolution, 3 channels)
    sequence_input = layers.Input(shape=input_shape)

    # Extract spatial features for each frame using 2D CNN
    cnn_model = build_cnn(input_shape=(64, 64, 3))

    # Apply CNN to each frame in the sequence
    time_distributed = layers.TimeDistributed(cnn_model)(sequence_input)

    # Process the sequence of CNN-extracted features using LSTM
    lstm_output, hidden_state, cell_state = layers.LSTM(lstm_units, return_sequences=True, return_state=True)(time_distributed)

    # Apply Bahdanau Attention
    attention_layer = BahdanauAttention(attention_units)
    context_vector, attention_weights = attention_layer(hidden_state, lstm_output)

    # Final Dense layer for classification
    outputs = layers.Dense(num_classes, activation='softmax')(context_vector)

    model = models.Model(inputs=sequence_input, outputs=outputs)
    return model

# Build the LRCN model with Bahdanau attention
lrcn_attention_model = build_lrcn_with_attention()

# Margin Triplet Loss function
def margin_triplet_loss(anchor, positive, negative, margin=1.0):
    """
    Computes the margin triplet loss.
    Args:
        anchor: Anchor embeddings.
        positive: Positive embeddings (same class as anchor).
        negative: Negative embeddings (different class than anchor).
        margin: The margin value to enforce the separation between positive and negative pairs.
    """
    # Compute the pairwise distances
    positive_distance = tf.reduce_sum(tf.square(anchor - positive), axis=-1)
    negative_distance = tf.reduce_sum(tf.square(anchor - negative), axis=-1)

    # Compute the triplet loss
    loss = tf.maximum(positive_distance - negative_distance + margin, 0.0)
    return tf.reduce_mean(loss)

# Generate triplets (anchor, positive, negative)
def create_triplet_contrastive_pairs(features, labels):
    triplet_pairs = []
    num_sequences = len(features)

    for i in range(num_sequences):
        anchor_seq = features[i]
        anchor_label = labels[i]

        # Find a positive example (same class)
        positive_indices = np.where(labels == anchor_label)[0]
        positive_idx = np.random.choice(positive_indices)
        positive_seq = features[positive_idx]

        # Find a negative example (different class)
        negative_indices = np.where(labels != anchor_label)[0]
        negative_idx = np.random.choice(negative_indices)
        negative_seq = features[negative_idx]

        triplet_pairs.append((anchor_seq, positive_seq, negative_seq))

    return triplet_pairs

# Pretrain the model using Margin Triplet Loss
def pretrain_triplet_contrastive_model(model, features, labels, epochs=10, batch_size=32):
    optimizer = tf.keras.optimizers.Adam()
    for epoch in range(epochs):
        print(f'Starting Epoch {epoch+1}/{epochs}')
        triplet_pairs = create_triplet_contrastive_pairs(features, labels)
        random.shuffle(triplet_pairs)  # Shuffle to ensure randomness

        batch_loss = []
        for i in range(0, len(triplet_pairs), batch_size):
            batch = triplet_pairs[i:i + batch_size]
            if len(batch) == 0:
                continue
            # Separate the triplets
            batch_anchor = [pair[0] for pair in batch]
            batch_positive = [pair[1] for pair in batch]
            batch_negative = [pair[2] for pair in batch]

            # Convert to tensors
            batch_anchor = tf.convert_to_tensor(batch_anchor, dtype=tf.float32)
            batch_positive = tf.convert_to_tensor(batch_positive, dtype=tf.float32)
            batch_negative = tf.convert_to_tensor(batch_negative, dtype=tf.float32)

            with tf.GradientTape() as tape:
                z_anchor = model(batch_anchor, training=True)
                z_positive = model(batch_positive, training=True)
                z_negative = model(batch_negative, training=True)

                loss = margin_triplet_loss(z_anchor, z_positive, z_negative)

            gradients = tape.gradient(loss, model.trainable_variables)
            optimizer.apply_gradients(zip(gradients, model.trainable_variables))
            batch_loss.append(loss.numpy())

        avg_loss = np.mean(batch_loss) if batch_loss else 0
        print(f'Epoch {epoch+1}, Average Loss: {avg_loss:.4f}')

# Pre-train the LRCN Model with Triplet Loss
