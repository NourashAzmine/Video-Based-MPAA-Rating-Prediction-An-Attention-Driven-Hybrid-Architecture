# Specify the height and width to which each video frame will be resized in our dataset.
IMAGE_HEIGHT, IMAGE_WIDTH = 64, 64

# Specify the number of frames of a video that will be fed to the model as one sequence.
SEQUENCE_LENGTH = 20

# Specify the directory containing the dataset.
DATASET_DIR = "Movie_dataset2"

# Specify the list containing the names of the classes used for training.
CLASSES_LIST = ["G", "PG", "PG-13", "R"]

# Function to extract, resize, and normalize frames
def frames_extraction(video_path):
    frames_list = []
    video_reader = cv2.VideoCapture(video_path)
    video_frames_count = int(video_reader.get(cv2.CAP_PROP_FRAME_COUNT))
    skip_frames_window = max(int(video_frames_count / SEQUENCE_LENGTH), 1)
    for frame_counter in range(SEQUENCE_LENGTH):
        video_reader.set(cv2.CAP_PROP_POS_FRAMES, frame_counter * skip_frames_window)
        success, frame = video_reader.read()
        if not success:
            break
        resized_frame = cv2.resize(frame, (IMAGE_HEIGHT, IMAGE_WIDTH))
        normalized_frame = resized_frame / 255
        frames_list.append(normalized_frame)
    video_reader.release()
    return frames_list

# Function to create the dataset
def create_dataset():
    features = []
    labels = []
    video_files_paths = []
    for class_index, class_name in enumerate(CLASSES_LIST):
        print(f'Extracting Data of Class: {class_name}')
        files_list = os.listdir(os.path.join(DATASET_DIR, class_name))
        for file_name in files_list:
            video_file_path = os.path.join(DATASET_DIR, class_name, file_name)
            frames = frames_extraction(video_file_path)
            if len(frames) == SEQUENCE_LENGTH:
                features.append(frames)
                labels.append(class_index)
                video_files_paths.append(video_file_path)
    features = np.asarray(features)
    labels = np.array(labels)
    return features, labels, video_files_paths

# Create the dataset
features, labels, video_files_paths = create_dataset()

# Convert labels to one-hot-encoded vectors
one_hot_encoded_labels = to_categorical(labels)

# Split the Data into Train (75%) and Test Set (25%)
features_train, features_test, labels_train, labels_test = train_test_split(
    features, one_hot_encoded_labels, test_size=0.25, shuffle=True, random_state=seed_constant
)

# Define data augmentation function for contrastive learning
def augment_frame(frame):
    frame = tf.image.random_flip_left_right(frame)
    frame = tf.image.random_brightness(frame, max_delta=0.2)
    frame = tf.image.random_contrast(frame, lower=0.8, upper=1.2)
    return frame

def create_contrastive_pairs(features):
    contrastive_pairs = []
    for frames in features:
        augmented_frames1 = [augment_frame(frame) for frame in frames]
        augmented_frames2 = [augment_frame(frame) for frame in frames]
        contrastive_pairs.append((augmented_frames1, augmented_frames2))
    return contrastive_pairs

from tensorflow.keras.layers import TimeDistributed
# Define the LRCN (CNN + LSTM) backbone
def build_lrcn_contrastive(input_shape=(20, 64, 64, 3), lstm_units=256):
    inputs = layers.Input(shape=input_shape)

    # CNN part
    x = TimeDistributed(layers.Conv2D(32, (3, 3), activation='relu'))(inputs)
    x = TimeDistributed(layers.MaxPooling2D((2, 2)))(x)
    x = TimeDistributed(layers.Conv2D(64, (3, 3), activation='relu'))(x)
    x = TimeDistributed(layers.MaxPooling2D((2, 2)))(x)
    x = TimeDistributed(layers.Conv2D(128, (3, 3), activation='relu'))(x)
    x = TimeDistributed(layers.MaxPooling2D((2, 2)))(x)

    # Flatten the feature maps to feed into LSTM
    x = TimeDistributed(layers.Flatten())(x)

    # LSTM part
    x = layers.LSTM(lstm_units, return_sequences=False)(x)

    model = models.Model(inputs, x)
    return model

# Build the LRCN-based contrastive model
lrcn_contrastive_model = build_lrcn_contrastive()

# Define the NT-Xent loss for contrastive learning
def nt_xent_loss(z_i, z_j, temperature=0.1):
    z_i = tf.math.l2_normalize(z_i, axis=1)
    z_j = tf.math.l2_normalize(z_j, axis=1)
    similarity_matrix = tf.matmul(z_i, z_j, transpose_b=True)
    positives = tf.linalg.diag_part(similarity_matrix)
    nominator = tf.exp(positives / temperature)
    denominator = tf.reduce_sum(tf.exp(similarity_matrix / temperature), axis=1)
    loss = -tf.reduce_mean(tf.math.log(nominator / denominator))
    return loss

# Pre-train the LRCN model with contrastive learning
def pretrain_contrastive_model(model, features, epochs=10, batch_size=32):
    optimizer = tf.keras.optimizers.Adam()
    for epoch in range(epochs):
        contrastive_pairs = create_contrastive_pairs(features)
        for augmented_frames1, augmented_frames2 in contrastive_pairs:
            # Add a batch dimension to the input data
            augmented_frames1 = tf.expand_dims(tf.convert_to_tensor(augmented_frames1, dtype=tf.float32), axis=0)
            augmented_frames2 = tf.expand_dims(tf.convert_to_tensor(augmented_frames2, dtype=tf.float32), axis=0)
            with tf.GradientTape() as tape:
                z_i = model(augmented_frames1, training=True)
                z_j = model(augmented_frames2, training=True)
                loss = nt_xent_loss(z_i, z_j)
            gradients = tape.gradient(loss, model.trainable_variables)
            optimizer.apply_gradients(zip(gradients, model.trainable_variables))
        print(f'Epoch {epoch+1}, Loss: {loss.numpy()}')

# Pre-train the LRCN model using contrastive learning
pretrain_contrastive_model(lrcn_contrastive_model, features_train)

# Add a classification head to the pre-trained LRCN model
def build_lrcn_with_classification(input_shape=(20, 64, 64, 3), num_classes=4, lstm_units=256):
    base_model = build_lrcn_contrastive(input_shape, lstm_units)
    x = base_model.output
    outputs = layers.Dense(num_classes, activation='softmax')(x)
    model = models.Model(base_model.input, outputs)
    return model

# Build and compile the final model for fine-tuning
lrcn_final_model = build_lrcn_with_classification()
lrcn_final_model.compile(loss='categorical_crossentropy', optimizer='Adam', metrics=['accuracy'])

# Fine-tune the model with labeled data
early_stopping_callback = EarlyStopping(monitor='val_loss', patience=10, mode='min', restore_best_weights=True)
history = lrcn_final_model.fit(
    x=features_train, y=labels_train, epochs=50, batch_size=4,
    shuffle=True, validation_split=0.2, callbacks=[early_stopping_callback]
)

# Evaluate the trained model on the test data
test_loss, test_accuracy = lrcn_final_model.evaluate(features_test, labels_test)
print(f'Test Loss: {test_loss}')
print(f'Test Accuracy: {test_accuracy}')

