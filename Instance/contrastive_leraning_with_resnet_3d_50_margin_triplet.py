# Define data augmentation function for contrastive learning
def augment_frame(frame):
    frame = tf.image.random_flip_left_right(frame)
    frame = tf.image.random_brightness(frame, max_delta=0.2)
    frame = tf.image.random_contrast(frame, lower=0.8, upper=1.2)
    return frame

def create_contrastive_pairs(features):
    contrastive_pairs = []
    for frames in features:
        augmented_frames1 = [augment_frame(frame) for frame in frames]
        augmented_frames2 = [augment_frame(frame) for frame in frames]
        contrastive_pairs.append((augmented_frames1, augmented_frames2))
    return contrastive_pairs

# Define the ResNet block
def res_block(x, filters, kernel_size=(3, 3, 3), stride=(1, 1, 1), block_id=1):
    y = layers.Conv3D(filters, kernel_size, strides=stride, padding='same', use_bias=False,
                      kernel_regularizer=regularizers.l2(1e-5),
                      name=f'conv{block_id}')(x)
    y = layers.BatchNormalization(name=f'bn{block_id}')(y)
    y = layers.ReLU(name=f'relu{block_id}')(y)
    y = layers.Conv3D(filters, kernel_size, padding='same', use_bias=False,
                      kernel_regularizer=regularizers.l2(1e-5),
                      name=f'conv{block_id}_2')(y)
    y = layers.BatchNormalization(name=f'bn{block_id}_2')(y)
    if x.shape[-1] != filters or stride != (1, 1, 1):
        x = layers.Conv3D(filters, (1, 1, 1), strides=stride, padding='same', use_bias=False,
                          kernel_regularizer=regularizers.l2(1e-5),
                          name=f'conv{block_id}_shortcut')(x)
        x = layers.BatchNormalization(name=f'bn{block_id}_shortcut')(x)
    y = layers.add([x, y])
    y = layers.ReLU(name=f'relu{block_id}_out')(y)
    return y

# Define the entire 3D ResNet-50 model for contrastive learning
def build_r3d_50_contrastive(input_shape=(20, 64, 64, 3)):
    inputs = layers.Input(shape=input_shape)
    x = layers.Conv3D(64, (5, 7, 7), strides=(2, 2, 2), padding='same', use_bias=False, name='conv1')(inputs)
    x = layers.BatchNormalization(name='bn1')(x)
    x = layers.ReLU(name='relu1')(x)
    x = layers.MaxPooling3D((1, 3, 3), strides=(1, 2, 2), padding='same', name='pool1')(x)
    x = res_block(x, 64, stride=(1, 1, 1), block_id=2)
    x = res_block(x, 128, stride=(2, 2, 2), block_id=3)
    x = res_block(x, 256, stride=(2, 2, 2), block_id=4)
    x = res_block(x, 512, stride=(2, 2, 2), block_id=5)
    x = layers.GlobalAveragePooling3D(name='gap')(x)
    model = models.Model(inputs, x)
    return model

# Build the model for contrastive learning
r3d_contrastive_model = build_r3d_50_contrastive()

# Define the Margin Triplet Loss Function
def margin_triplet_loss(anchor, positive, negative, margin=1.0):
    positive_distance = tf.reduce_sum(tf.square(anchor - positive), axis=-1)
    negative_distance = tf.reduce_sum(tf.square(anchor - negative), axis=-1)
    loss = tf.maximum(positive_distance - negative_distance + margin, 0.0)
    return tf.reduce_mean(loss)

# Modify Pre-Training Loop
def create_triplet_pairs(features):
    triplet_pairs = []
    for frames in features:
        augmented_frames1 = [augment_frame(frame) for frame in frames]
        augmented_frames2 = [augment_frame(frame) for frame in frames]
        random_idx = random.randint(0, len(features) - 1)
        negative_frames = [augment_frame(frame) for frame in features[random_idx]]
        triplet_pairs.append((augmented_frames1, augmented_frames2, negative_frames))
    return triplet_pairs

def pretrain_triplet_model(model, features, epochs=10, batch_size=32):
    optimizer = tf.keras.optimizers.Adam()
    for epoch in range(epochs):
        triplet_pairs = create_triplet_pairs(features)
        for anchor_frames, positive_frames, negative_frames in triplet_pairs:
            anchor_frames = tf.expand_dims(tf.convert_to_tensor(anchor_frames, dtype=tf.float32), axis=0)
            positive_frames = tf.expand_dims(tf.convert_to_tensor(positive_frames, dtype=tf.float32), axis=0)
            negative_frames = tf.expand_dims(tf.convert_to_tensor(negative_frames, dtype=tf.float32), axis=0)
            with tf.GradientTape() as tape:
                z_anchor = model(anchor_frames, training=True)
                z_positive = model(positive_frames, training=True)
                z_negative = model(negative_frames, training=True)
                loss = margin_triplet_loss(z_anchor, z_positive, z_negative)
            gradients = tape.gradient(loss, model.trainable_variables)
            optimizer.apply_gradients(zip(gradients, model.trainable_variables))
        print(f'Epoch {epoch+1}, Loss: {loss.numpy()}')

# Pre-train the model using margin triplet loss
pretrain_triplet_model(r3d_contrastive_model, features_train)

# Add a classification head to the pre-trained model
def build_r3d_50_with_classification(input_shape=(20, 64, 64, 3), num_classes=4):
    base_model = build_r3d_50_contrastive(input_shape)
    x = base_model.output
    outputs = layers.Dense(num_classes, activation='softmax')(x)
    model = models.Model(base_model.input, outputs)
    return model

# Build and compile the final model for fine-tuning
r3d_final_model = build_r3d_50_with_classification()
r3d_final_model.compile(loss='categorical_crossentropy', optimizer='Adam', metrics=['accuracy'])

# Fine-tune the model with labeled data
early_stopping_callback = EarlyStopping(monitor='val_loss', patience=10, mode='min', restore_best_weights=True)
r3d_final_model.fit(
    x=features_train, y=labels_train, epochs=50, batch_size=4,
    shuffle=True, validation_split=0.2, callbacks=[early_stopping_callback]
)

# Evaluate the trained model on the test data
test_loss, test_accuracy = r3d_final_model.evaluate(features_test, labels_test)
