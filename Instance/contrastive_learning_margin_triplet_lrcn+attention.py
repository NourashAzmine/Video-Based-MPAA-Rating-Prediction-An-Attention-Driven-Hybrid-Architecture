# Define data augmentation function for contrastive learning
def augment_frame(frame):
    frame = tf.image.random_flip_left_right(frame)
    frame = tf.image.random_brightness(frame, max_delta=0.2)
    frame = tf.image.random_contrast(frame, lower=0.8, upper=1.2)
    return frame

# Create contrastive pairs
def create_contrastive_pairs(features):
    contrastive_pairs = []
    for frames in features:
        augmented_frames1 = [augment_frame(frame) for frame in frames]
        augmented_frames2 = [augment_frame(frame) for frame in frames]
        contrastive_pairs.append((augmented_frames1, augmented_frames2))
    return contrastive_pairs

# Define the LRCN (CNN + LSTM) backbone with attention
class AttentionLayer(layers.Layer):
    def __init__(self):
        super(AttentionLayer, self).__init__()

    def build(self, input_shape):
        self.W = self.add_weight(name="attention_weight", shape=(input_shape[-1], input_shape[-1]), initializer="glorot_uniform", trainable=True)
        self.b = self.add_weight(name="attention_bias", shape=(input_shape[-1],), initializer="zeros", trainable=True)
        self.u = self.add_weight(name="context_vector", shape=(input_shape[-1],), initializer="glorot_uniform", trainable=True)

    def call(self, x):
        u_t = tf.tanh(tf.tensordot(x, self.W, axes=1) + self.b)
        a_t = tf.tensordot(u_t, self.u, axes=1)
        a_t = tf.nn.softmax(a_t, axis=1)
        output = tf.reduce_sum(x * tf.expand_dims(a_t, -1), axis=1)
        return output

# Modify the LRCN model to include an attention mechanism
def build_lrcn_with_attention(input_shape=(20, 64, 64, 3), num_classes=4, lstm_units=256):
    inputs = layers.Input(shape=input_shape)

    # CNN part
    x = TimeDistributed(layers.Conv2D(32, (3, 3), activation='relu'))(inputs)
    x = TimeDistributed(layers.MaxPooling2D((2, 2)))(x)
    x = TimeDistributed(layers.Conv2D(64, (3, 3), activation='relu'))(x)
    x = TimeDistributed(layers.MaxPooling2D((2, 2)))(x)
    x = TimeDistributed(layers.Conv2D(128, (3, 3), activation='relu'))(x)
    x = TimeDistributed(layers.MaxPooling2D((2, 2)))(x)

    # Flatten the feature maps to feed into LSTM
    x = TimeDistributed(layers.Flatten())(x)

    # LSTM part
    x = layers.LSTM(lstm_units, return_sequences=True)(x)

    # Apply attention layer
    x = AttentionLayer()(x)

    # Output layer
    outputs = layers.Dense(num_classes, activation='softmax')(x)

    model = models.Model(inputs, outputs)
    return model

# Build and compile the final model with attention mechanism for fine-tuning
lrcn_attention_model = build_lrcn_with_attention()
lrcn_attention_model.compile(loss='categorical_crossentropy', optimizer='Adam', metrics=['accuracy'])

def margin_triplet_loss(anchor, positive, negative, margin=1.0):
    # Normalize embeddings
    anchor = tf.math.l2_normalize(anchor, axis=1)
    positive = tf.math.l2_normalize(positive, axis=1)
    negative = tf.math.l2_normalize(negative, axis=1)

    # Calculate positive and negative distances
    pos_dist = tf.reduce_sum(tf.square(anchor - positive), axis=-1)
    neg_dist = tf.reduce_sum(tf.square(anchor - negative), axis=-1)

    # Calculate triplet loss
    loss = tf.maximum(0.0, pos_dist - neg_dist + margin)
    return tf.reduce_mean(loss)

# Modify the pre-training function to use the margin triplet loss
def pretrain_with_triplet_loss(model, features, epochs=10, batch_size=32):
    optimizer = tf.keras.optimizers.Adam()
    for epoch in range(epochs):
        triplet_pairs = create_triplet_pairs(features)  # Create triplet pairs for the loss
        for anchor_frames, positive_frames, negative_frames in triplet_pairs:
            anchor_frames = tf.expand_dims(tf.convert_to_tensor(anchor_frames, dtype=tf.float32), axis=0)
            positive_frames = tf.expand_dims(tf.convert_to_tensor(positive_frames, dtype=tf.float32), axis=0)
            negative_frames = tf.expand_dims(tf.convert_to_tensor(negative_frames, dtype=tf.float32), axis=0)
            with tf.GradientTape() as tape:
                anchor_embedding = model(anchor_frames, training=True)
                positive_embedding = model(positive_frames, training=True)
                negative_embedding = model(negative_frames, training=True)
                loss = margin_triplet_loss(anchor_embedding, positive_embedding, negative_embedding)
            gradients = tape.gradient(loss, model.trainable_variables)
            optimizer.apply_gradients(zip(gradients, model.trainable_variables))
        print(f'Epoch {epoch+1}, Loss: {loss.numpy()}')

# Function to create triplet pairs (anchor, positive, negative) from the features
def create_triplet_pairs(features):
    triplet_pairs = []
    for i in range(len(features)):
        anchor_frames = features[i]
        positive_index = random.choice([j for j in range(len(features)) if j != i])
        positive_frames = features[positive_index]
        negative_index = random.choice([j for j in range(len(features)) if j != i])
        negative_frames = features[negative_index]
        triplet_pairs.append((anchor_frames, positive_frames, negative_frames))
    return triplet_pairs

